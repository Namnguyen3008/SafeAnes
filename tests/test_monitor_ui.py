"""The redesigned monitor: numerics, alarms on screen, display controls, CPR,
scenarios and the event log - driven through the real window.

Signal is generated by running the engine straight into the ring buffer, so a
test can put 30 seconds of any rhythm on screen in a fraction of a second, then
call the window's own update tick.

Run directly (``python tests/test_monitor_ui.py``) or under pytest.
"""

