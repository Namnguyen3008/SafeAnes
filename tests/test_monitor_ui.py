def test_freeze_holds_the_picture_while_the_patient_continues():
    window, _, generator = live(10.0)
    try:
        window.monitor.refresh()
        before = window.monitor.ecg_curve.yData.copy()
        window.toggle_freeze()
        assert window.monitor.frozen and window.freeze_button.isChecked()
        run(window, 2.0)
        window.monitor.refresh()
        assert np.array_equal(before, window.monitor.ecg_curve.yData, equal_nan=True)
        assert window._buffer.total_written > 10_000, "simulation stopped with the display"

        window.toggle_freeze()
        window.monitor.refresh()
        assert not np.array_equal(before, window.monitor.ecg_curve.yData, equal_nan=True)
    finally:
        window.close()


