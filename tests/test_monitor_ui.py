# --- debouncing ---------------------------------------------------------------------
def test_tracker_ignores_blips_and_holds_through_dips():
    alarm = Alarm("hr_low", HIGH, "hr", "HR LOW 40")
    tracker = AlarmTracker(onset_s=1.0, clear_s=3.0)
    assert tracker.update([alarm], 0.0)[1] == []          # first sighting: pending
    assert tracker.update([], 0.5)[0] == []               # a blip: never raised
    tracker.update([alarm], 1.0)
    active, raised, _ = tracker.update([alarm], 2.0)
    assert raised == [alarm] and active == [alarm]
    assert tracker.update([], 2.5)[0] == [alarm], "a momentary dip must not clear it"
    _, _, cleared = tracker.update([], 5.1)
    assert cleared == [alarm]


def test_tracker_keeps_the_message_current():
    tracker = AlarmTracker(onset_s=0.0)
    tracker.update([Alarm("hr_high", MEDIUM, "hr", "HR HIGH 130")], 0.0)
    active, _, _ = tracker.update([Alarm("hr_high", MEDIUM, "hr", "HR HIGH 142")], 0.5)
    assert active[0].message == "HR HIGH 142"


def _alarm_entries(window: MainWindow) -> list[str]:
    return [m for m in window.controls.event_log.messages()
            if "Alarm:" in m or "Cleared:" in m]


def test_a_rate_sitting_on_its_limit_does_not_flood_the_log():
    """Respiratory sinus arrhythmia swings a 120 bpm rate either side of a
    120 bpm limit every breath.  Undebounced, that is an alarm and a clear
    every few seconds; the tracker has to absorb it.

    Compared against an undebounced run of the same patient, so the test fails
    if the scenario stops flapping - rather than passing because it never did.
    """
    def entries(tracker: AlarmTracker | None) -> list[str]:
        window, _, _ = live(12.0, heart_rate=120)
        try:
            window.controls.limit_spins["hr_high"].setValue(120)
            if tracker is not None:
                window.alarm_tracker = tracker
            window.controls.event_log.clear()
            run(window, 60.0)
            return _alarm_entries(window)
        finally:
            window.close()

    raw = entries(AlarmTracker(onset_s=0.0, clear_s=0.0))
    debounced = entries(None)
    assert len(raw) >= 10, f"scenario no longer flaps ({len(raw)} raw entries)"
    assert len(debounced) <= len(raw) // 4, f"{len(debounced)} vs {len(raw)} undebounced"


def test_cleared_alarms_are_logged_in_words_not_codes():
    window, state, _ = live(15.0, cardiac_rhythm="V-Fib")
    try:
        state.update(cardiac_rhythm="Sinus")
        window.controls.event_log.clear()
        run(window, 15.0)
        cleared = [m for m in _alarm_entries(window) if "Cleared:" in m]
        assert cleared, "recovering from VF should clear its alarms"
        assert not any("_" in m for m in cleared), f"internal codes leaked: {cleared}"
    finally:
        window.close()


