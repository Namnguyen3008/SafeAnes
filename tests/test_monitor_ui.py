def test_the_whole_window_stays_responsive_with_the_producer_running():
    state = SimulationState()
    buffer = RingBuffer()
    generator = SignalGenerator(state, buffer)
    window = MainWindow(state.snapshot())
    window.bind(state, buffer, generator)
    window.resize(1480, 900)
    window.show()
    generator.start()
    try:
        worst = 0.0
        deadline = time.perf_counter() + 12.0
        while time.perf_counter() < deadline:
            started = time.perf_counter()
            APP.processEvents()
            window.monitor.refresh()
            APP.processEvents()
            worst = max(worst, time.perf_counter() - started)
            time.sleep(0.02)
        assert buffer.total_written > 10_000, "buffer never filled"
        assert worst < 0.25, f"a frame took {worst * 1000:.0f} ms with the buffer full"
    finally:
        window.close()


