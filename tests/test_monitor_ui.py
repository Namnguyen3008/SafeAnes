def test_scenario_runs_from_the_panel():
    window, state, _ = live(5.0)
    try:
        c = window.controls
        c.scenario_list.setCurrentRow(list(SCENARIOS).index("Evolving heart block"))
        c.scenario_button.click()
        assert window.player.running
        assert window.scenario_chip.isVisibleTo(window)
        assert "Stop" in c.scenario_button.text() and not c.scenario_list.isEnabled()

        window.player._started -= 30.0                   # jump ahead in scenario time
        run(window, 1.0)
        assert state.snapshot().cardiac_rhythm == "Mobitz I (Wenckebach)"
        assert c.rhythm_combo.currentText() == "Mobitz I (Wenckebach)", "panel not synced"

        c.scenario_button.click()
        assert not window.player.running and c.scenario_list.isEnabled()
    finally:
        window.close()


