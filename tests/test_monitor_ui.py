def live(seconds: float = 30.0, **params):
    """A bound window whose buffer already holds ``seconds`` of the given patient."""
    state = SimulationState(**params)
    buffer = RingBuffer()
    generator = SignalGenerator(state, buffer, rng=np.random.default_rng(5))
    window = MainWindow(state.snapshot())
    window.bind(state, buffer, generator)
    run(window, seconds)
    return window, state, generator


def run(window: MainWindow, seconds: float) -> None:
    """Advance the simulation, ticking the window every half second as it would."""
    generator, buffer = window._generator, window._buffer
    for i in range(int(seconds * 20)):
        buffer.write(generator.engine.next_chunk(50))
        if i % 10 == 9:
            window.refresh_vitals()


# --- numerics on screen ---------------------------------------------------------
def test_tiles_show_what_was_measured():
    # Pressure targets are calibrated at the reference 72 bpm; at any other rate
    # the arterial line legitimately reads something else (see the next test).
    window, _, _ = live(heart_rate=72, systolic=130, diastolic=85, spo2_target=95)
    try:
        m = window.monitor
        assert abs(int(m.hr_tile.value_text) - 72) <= 3
        assert m.spo2_tile.value_text == "95"
        sys_, dia = (int(x) for x in m.abp_tile.value_text.split("/"))
        assert abs(sys_ - 130) <= 4 and abs(dia - 85) <= 4
        assert m.rr_tile.value_text == "15"
    finally:
        window.close()


def test_a_faster_heart_raises_the_measured_pressure():
    slow, _, _ = live(heart_rate=72)
    fast, _, _ = live(heart_rate=110)
    try:
        mean = lambda w: int(w.monitor.abp_tile.sub_label.text().strip("()"))   # noqa: E731
        assert mean(fast) > mean(slow) + 5, (mean(slow), mean(fast))
    finally:
        slow.close()
        fast.close()


